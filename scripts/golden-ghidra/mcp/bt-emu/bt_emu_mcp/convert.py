"""Turn a captured GATT database into a profile skeleton.

Two input formats:

``bluetoothctl``
    The text printed by ``bluetoothctl`` -> ``menu gatt`` -> ``list-attributes <addr>``
    (``Primary Service (Handle 0x..)`` / ``Characteristic (Handle 0x..)`` /
    ``Descriptor (Handle 0x..)`` blocks, each followed by a D-Bus path and a UUID line).
    That output carries no properties or values, so those are written as unknown
    unless supplied through ``--values``.

``json``
    ``{"services": [{"uuid", "characteristics": [{"uuid", "properties": [...], "value_hex": "..",
    "descriptors": [...]}]}]}`` - the shape returned by this server's ``gatt_dump`` tool
    (``--format json`` accepts that output directly), or anything you transcribe from
    nRF Connect / btmon in the same shape.

``--values`` is a JSON object ``{"<char uuid>": {"properties": [...], "value_hex": "..."}}`` used to
attach what you read from the real device.  Anything not supplied stays unknown.

    python -m bt_emu_mcp.convert capture.txt --id my-buds --name "My Buds" --address AA:BB:CC:DD:EE:FF > my-buds.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from typing import Any

from .profiles import validate

_BASE = "-0000-1000-8000-00805f9b34fb"
_AUTO = {"1800", "1801"}
_HEADER = re.compile(r"^\s*(Primary Service|Secondary Service|Characteristic|Descriptor)\s*\(Handle\s+(0x[0-9a-fA-F]+)\)")
_UUID = re.compile(r"^\s*([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})\s*$")


def short(uuid: str) -> str:
    u = uuid.lower()
    if u.startswith("0000") and u.endswith(_BASE):
        return u[4:8].upper()
    return u


def parse_bluetoothctl(text: str) -> dict[str, Any]:
    services: list[dict[str, Any]] = []
    kind: str | None = None
    for line in text.splitlines():
        m = _HEADER.match(line)
        if m:
            kind = m.group(1)
            continue
        m = _UUID.match(line)
        if m and kind:
            uuid = short(m.group(1))
            if kind.endswith("Service"):
                services.append({"uuid": uuid, "characteristics": []})
            elif kind == "Characteristic" and services:
                services[-1]["characteristics"].append({"uuid": uuid})
            elif kind == "Descriptor" and services and services[-1]["characteristics"]:
                services[-1]["characteristics"][-1].setdefault("descriptors", []).append({"uuid": uuid})
            kind = None
    return {"services": services}


def build_profile(capture: dict[str, Any], pid: str, name: str, address: str | None, values: dict[str, Any]) -> dict[str, Any]:
    vals = {short(k) if len(k) == 36 else k.upper(): v for k, v in values.items()}
    services = []
    for svc in capture.get("services", []):
        suuid = short(svc["uuid"]) if len(svc["uuid"]) == 36 else svc["uuid"]
        if suuid.upper() in _AUTO:
            continue  # GAP / GATT are added automatically by the emulator
        chars = []
        for ch in svc.get("characteristics", []):
            cuuid = short(ch["uuid"]) if len(ch["uuid"]) == 36 else ch["uuid"]
            extra = vals.get(cuuid.upper(), vals.get(cuuid, {}))
            out: dict[str, Any] = {"uuid": cuuid}
            unknown = []
            props = extra.get("properties", ch.get("properties"))
            if props:
                out["properties"] = [p for p in props if p != "write_without_resp"]
            else:
                unknown.append("properties")
            val = extra.get("value_hex", ch.get("value_hex"))
            if val is not None and val != "<dynamic>":
                out["value_hex"] = val
            else:
                unknown.append("value_hex")
            descs = [
                {"uuid": short(d["uuid"]) if len(d.get("uuid", "")) == 36 else d["uuid"],
                 **({"value_hex": d["value_hex"]} if d.get("value_hex") not in (None, "<dynamic>") else {})}
                for d in ch.get("descriptors", [])
                if (short(d["uuid"]) if len(d.get("uuid", "")) == 36 else d.get("uuid", "")).upper() != "2902"
            ]
            if descs:
                out["descriptors"] = descs
            if unknown:
                out["unknown_fields"] = unknown
            chars.append(out)
        services.append({"uuid": suuid, "characteristics": chars})
    profile: dict[str, Any] = {
        "schema_version": 1, "id": pid, "name": name, "skeleton": True,
        "description": "Generated by bt_emu_mcp.convert from a GATT capture; review before relying on it.",
        "gatt": {"services": services},
        "advertising": {"unknown": True}, "scan_response": {"unknown": True},
        "a2dp_sink": {"unknown": True}, "avrcp": {"unknown": True},
        "provenance": {"source": "bt_emu_mcp.convert", "still_needs_capture": ["advertising payload", "scan response", "a2dp/avrcp capabilities", "anything marked unknown_fields"]},
    }
    if address:
        profile["address"] = address
    return profile


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("capture", help="capture file ('-' for stdin)")
    ap.add_argument("--format", choices=["bluetoothctl", "json"], default="bluetoothctl")
    ap.add_argument("--id", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--address")
    ap.add_argument("--values", help="JSON file with properties/values read from the real device")
    args = ap.parse_args(argv)
    text = sys.stdin.read() if args.capture == "-" else open(args.capture).read()
    data = parse_bluetoothctl(text) if args.format == "bluetoothctl" else json.loads(text)
    if "services" not in data and "result" in data:
        data = data["result"]
    values = json.load(open(args.values)) if args.values else {}
    profile = build_profile(data, args.id, args.name, args.address, values)
    problems = validate(profile)
    if problems:
        print("generated profile is invalid: " + "; ".join(problems[:5]), file=sys.stderr)
        return 1
    json.dump(profile, sys.stdout, indent=2)
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
